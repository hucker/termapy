"""Sync the format-spec type table -> the help page and README tables.

One source of truth (``src/termapy/protocol/type_codes.py``, the
``TYPE_CODES`` table).  Every block between the markers

    <!-- format-types:start ... -->
    <!-- format-types:end -->

in the target files is regenerated from it.  The Output column is not
copied from the table: each example is decoded from its row's ``sample``
by the real ``parse_format_spec`` / ``apply_format``, and an example that
does not parse to its own row's code fails the sync -- so a documented
output cannot disagree with the decoder.

Usage (needs the project environment, it runs the decoder):
    uv run python scripts/sync_format_tables.py          # writes if drifted
    uv run python scripts/sync_format_tables.py --check  # exit 1 if drifted

``tests/test_format_tables_sync.py`` runs ``--check``, so a hand edit to a
generated table fails the suite.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGETS = (
    REPO_ROOT / "src" / "termapy" / "help" / "protocol-testing.md",
    REPO_ROOT / "README.md",
)

sys.path.insert(0, str(REPO_ROOT / "src"))
from termapy.protocol.core import apply_format, parse_format_spec  # noqa: E402 -- path set above
from termapy.protocol.type_codes import TYPE_CODES, TypeCode  # noqa: E402 -- path set above

_START = (
    "<!-- format-types:start (generated by scripts/sync_format_tables.py"
    " from protocol/type_codes.py -- do not edit by hand) -->"
)
_END = "<!-- format-types:end -->"
_BLOCK_RE = re.compile(r"<!-- format-types:start[^\n]*-->\n.*?" + re.escape(_END), re.DOTALL)
_HEADER = ("Code", "Meaning", "Example", "Output")


def _decode(entry: TypeCode, example: str) -> str:
    """Decode one example over the row's sample, checking it is the row's own code."""
    columns = parse_format_spec(f"X:{example}")
    expected_code = "crc" if entry.kind == "crc" else entry.code
    if columns[0].type_code != expected_code:
        raise ValueError(
            f"example {example!r} parses as {columns[0].type_code!r}, "
            f"not as its row's code {entry.code!r}"
        )
    if entry.output:
        return ""
    _, values = apply_format(entry.sample, columns)
    return values[0]


def _row(entry: TypeCode) -> tuple[str, str, str, str]:
    """One table row's four cells."""
    decoded = [_decode(entry, example) for example in entry.examples]
    output = entry.output or ", ".join(f"`{value}`" for value in decoded)
    examples = ", ".join(f"`{example}`" for example in entry.examples)
    return (f"`{entry.code}`", entry.meaning, examples, output)


def render_table(entries: tuple[TypeCode, ...] = TYPE_CODES) -> str:
    """The markdown table for ``entries`` (TYPE_CODES), columns padded to align."""
    rows = [_HEADER, *(_row(entry) for entry in entries)]
    widths = [max(len(row[i]) for row in rows) for i in range(len(_HEADER))]

    def line(cells: tuple[str, ...]) -> str:
        return "| " + " | ".join(cell.ljust(width) for cell, width in zip(cells, widths)) + " |"

    rule = "| " + " | ".join("-" * width for width in widths) + " |"
    return "\n".join([line(rows[0]), rule, *(line(row) for row in rows[1:])])


def render_block() -> str:
    """The full generated block, markers included."""
    return f"{_START}\n\n{render_table()}\n\n{_END}"


def rewrite(text: str, path: Path) -> str:
    """Return ``text`` with every format-types block regenerated.

    Raises if the file has no block, so a deleted marker fails loudly
    instead of silently leaving a hand-kept table behind.
    """
    block = render_block()
    new_text, count = _BLOCK_RE.subn(lambda _match: block, text)
    if count == 0:
        raise RuntimeError(
            f"format-types:start / format-types:end markers not found in {path.name}"
        )
    return new_text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if a generated table is out of sync (do not modify).",
    )
    args = parser.parse_args(argv)

    stale: list[Path] = []
    for path in TARGETS:
        text = path.read_text(encoding="utf-8")
        new_text = rewrite(text, path)
        if new_text == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(new_text, encoding="utf-8")
            print(f"OK  {path.relative_to(REPO_ROOT)} type table regenerated")

    if not stale:
        print("OK  format-spec type tables are in sync with protocol/type_codes.py")
        return 0
    if args.check:
        names = ", ".join(str(path.relative_to(REPO_ROOT)) for path in stale)
        print(
            f"FAIL {names} out of sync with protocol/type_codes.py.\n"
            "     Run: uv run python scripts/sync_format_tables.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
