"""Regenerate docs/traceability-matrix.md from the ``rule`` markers under tests/.

The matrix is the generated half of traceability: a table of the ids no test
pins, then one section per id source (``tests/traceability.py`` ``SOURCES``:
the rule registry ``docs/rules.md`` and each spec that labels its sections
with ids) listing every test that pins each id, by file, with the tests a
registry row names as the rule's guard marked.  A requirements file added as a
source gets its own section with no change here.  ``tests/test_traceability.py``
fails when the file is stale or hand-edited::

    uv run python scripts/sync_traceability.py          # rewrite
    uv run python scripts/sync_traceability.py --check  # exit 1 when stale

Stdlib only, plus ``tests/traceability.py`` for the index.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MATRIX = REPO_ROOT / "docs" / "traceability-matrix.md"

sys.path.insert(0, str(REPO_ROOT / "tests"))
from traceability import (  # noqa: E402 -- path set above
    PROBE_REF,
    SOURCES,
    TEST_REF,
    FileEntry,
    MarkIndex,
    index_tests,
    matrix_entries,
    registry_ids,
    registry_rows,
)

# (title, file name, ids): one section of the matrix besides the registry's.
Section = tuple[str, str, set[str]]

_INTRO = """\
# Traceability matrix

<!-- generated by scripts/sync_traceability.py from the rule markers under tests/; do not edit -->

Every test that pins an id, by id. The ids come from the id sources in
`tests/traceability.py` (`SOURCES`): today the [rule registry](rules.md) and a
spec that labels its sections with ids, later the requirement documents as
they are written. Under each id, every test that carries
`@pytest.mark.rule("<id>")`, by file. A test the registry row names as the
rule's guard is marked **guard**, its probe **probe**; a whole module or a
class that carries the marker is listed once with its test count. The first
table is the ids no test pins. The process is [traceability.md](traceability.md).
"""


def _label(name: str, guards: set[str], probes: set[str]) -> str:
    """A test's name in backticks, marked when the row names it."""
    short = name.rsplit(".", 1)[-1]
    if short in probes or name in probes:
        return f"`{name}` **probe**"
    if short in guards or name in guards:
        return f"`{name}` **guard**"
    return f"`{name}`"


def _file_line(file: str, entry: FileEntry, guards: set[str], probes: set[str]) -> str:
    """One bullet: what a file contributes to an id."""
    parts: list[str] = []
    if entry.module:
        mark = " **guard**" if file in guards else ""
        parts.append(f"the module ({entry.module_functions} functions){mark}")
    for qualname, count in sorted(entry.classes):
        parts.append(f"{_label(qualname, guards, probes)} ({count} functions)")
    for qualname in sorted(entry.functions):
        parts.append(_label(qualname, guards, probes))
    return f"- `{file}`: {', '.join(parts)}"


def _id_section(
    rule_id: str,
    heading_note: str,
    files: dict[str, FileEntry],
    enforced_by: str,
) -> list[str]:
    guards = set(TEST_REF.findall(enforced_by))
    probes = set(PROBE_REF.findall(enforced_by))
    lines = [f"### `{rule_id}` ({heading_note})", ""]
    if not files:
        lines.append("- no tagged test")
    else:
        lines.extend(_file_line(file, files[file], guards, probes) for file in sorted(files))
    lines.append("")
    return lines


def _row_note(row: dict[str, str]) -> str:
    return f"{row.get('kind', '')}, {row.get('category', '')}"


def _missing_table(
    registry: dict[str, dict[str, str]],
    registry_file: str,
    sections: list[Section],
    pinned: set[str],
) -> list[str]:
    """The ids no test pins, one row each, the registry's first."""
    rows = [
        f"| `{rule_id}` | `{registry_file}` | {_row_note(registry[rule_id])} |"
        for rule_id in sorted(registry)
        if rule_id not in pinned
    ]
    for title, file, ids in sections:
        rows.extend(
            f"| `{rule_id}` | `{file}` | {title.lower()} section |"
            for rule_id in sorted(ids)
            if rule_id not in pinned
        )
    lines = ["## Pinned by no test", ""]
    if not rows:
        lines.append("Every id is pinned by at least one test.")
    else:
        lines.extend(["| id | source | kind |", "|---|---|---|", *rows])
    lines.append("")
    return lines


def render_matrix(
    rows: list[dict[str, str]],
    sections: list[Section],
    index: MarkIndex,
    *,
    registry_file: str = "rules.md",
) -> str:
    """The whole matrix: the summary, the unpinned ids, the registry's rows, then each other source's ids."""
    entries = matrix_entries(index)
    registry = {row["id"]: row for row in rows}
    all_ids = set(registry) | {rule_id for _, _, ids in sections for rule_id in ids}
    pinned = {rule_id for rule_id in all_ids if entries.get(rule_id)}
    guarantees = sum(1 for row in rows if row.get("kind") == "guarantee")
    counts = [
        f"{len(registry)} registry rows (guarantees {guarantees}, assumptions {len(registry) - guarantees})"
    ]
    counts.extend(
        f"{len(ids)} {title.lower()} sections in `{file}`" for title, file, ids in sections
    )
    lines = [
        _INTRO,
        f"Ids: {len(all_ids)}: {', '.join(counts)}. "
        f"Pinned by at least one test: {len(pinned)}. Pinned by none: {len(all_ids - pinned)}.",
        "",
        *_missing_table(registry, registry_file, sections, pinned),
        f"## Registry (`{registry_file}`)",
        "",
    ]
    for rule_id in sorted(registry):
        row = registry[rule_id]
        lines.extend(
            _id_section(
                rule_id, _row_note(row), entries.get(rule_id, {}), row.get("enforced by", "")
            )
        )
    for title, file, ids in sections:
        lines.extend([f"## {title} (`{file}`)", ""])
        for rule_id in sorted(ids):
            lines.extend(
                _id_section(rule_id, f"{title.lower()} section", entries.get(rule_id, {}), "")
            )
    return "\n".join(lines).rstrip("\n") + "\n"


def render() -> str:
    """The matrix for the repository as it stands."""
    rows: list[dict[str, str]] = []
    registry_file = "rules.md"
    sections: list[Section] = []
    for source in SOURCES:
        if source.parse is registry_ids:
            rows = registry_rows(source.path.read_text(encoding="utf-8"))
            registry_file = source.path.name
        else:
            sections.append((source.title, source.path.name, source.ids()))
    return render_matrix(rows, sections, index_tests(), registry_file=registry_file)


def main(argv: list[str] | None = None) -> int:
    """Rewrite the matrix, or with ``--check`` report whether it is current."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is stale")
    args = parser.parse_args(argv)
    text = render()
    current = MATRIX.read_text(encoding="utf-8") if MATRIX.exists() else ""
    if args.check:
        if current == text:
            print(f"{MATRIX.relative_to(REPO_ROOT)} is current")
            return 0
        print(
            f"{MATRIX.relative_to(REPO_ROOT)} is stale; run: uv run python scripts/sync_traceability.py"
        )
        return 1
    if current == text:
        print(f"{MATRIX.relative_to(REPO_ROOT)} unchanged")
    else:
        MATRIX.write_text(text, encoding="utf-8", newline="\n")
        print(f"{MATRIX.relative_to(REPO_ROOT)} updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
